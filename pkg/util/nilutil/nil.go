// Package nilutil checks interfaces that may contain typed nil values.
package nilutil

import "reflect"

// IsNilInterface reports whether value is nil or holds a nil reference value.
// Non-nilable values, including their zero values, are not nil.
func IsNilInterface(value any) bool {
	if value == nil {
		return true
	}
	v := reflect.ValueOf(value)
	switch v.Kind() {
	case reflect.Chan, reflect.Func, reflect.Interface, reflect.Map, reflect.Pointer, reflect.Slice, reflect.UnsafePointer:
		return v.IsNil()
	default:
		return false
	}
}
