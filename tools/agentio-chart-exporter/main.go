const (
	valuesBegin = "# BEGIN GENERATED AGENTIO VALUES - DO NOT EDIT"
	valuesEnd   = "# END GENERATED AGENTIO VALUES"
	warning     = "{{/* Code generated by agentio-chart-exporter. DO NOT EDIT. */}}\n"
)

var (
	definePattern = regexp.MustCompile(`\{\{-?\s*define\s+`)
	filesPattern  = regexp.MustCompile(`((?:\$)?\.Files\.(?:Get|Glob)\s+)"files/`)
)

func main() {
	source := flag.String("source", "", "prepared Agentio chart directory")
	target := flag.String("target", "", "sandbox-manager chart directory")
	flag.Parse()

	if *source == "" || *target == "" {
		fmt.Fprintln(os.Stderr, "--source and --target are required")
		os.Exit(2)
	}
	if err := Export(*source, *target); err != nil {
		fmt.Fprintf(os.Stderr, "export Agentio chart: %v\n", err)
		os.Exit(1)
	}
}

// Export converts a standalone Agentio chart into generated, optional
// sandbox-manager templates and values.
func Export(source, target string) error {
	sourceValuesPath := filepath.Join(source, "values.yaml")
	sourceValues, err := os.ReadFile(sourceValuesPath)
	if err != nil {
		return fmt.Errorf("read source values: %w", err)
	}
	if err := validateSourceValues(sourceValues); err != nil {
		return err
	}

	targetValuesPath := filepath.Join(target, "values.yaml")
	targetValues, err := os.ReadFile(targetValuesPath)
	if err != nil {
		return fmt.Errorf("read target values: %w", err)
	}
	nextValues, err := replaceValuesBlock(targetValues, sourceValues)
	if err != nil {
		return err
	}

	templatesSource := filepath.Join(source, "templates")
	filesSource := filepath.Join(source, "files")
	if info, err := os.Stat(templatesSource); err != nil || !info.IsDir() {
		if err == nil {
			err = errors.New("not a directory")
		}
		return fmt.Errorf("validate source templates: %w", err)
	}

	staging, err := os.MkdirTemp(target, ".agentio-chart-export-")
	if err != nil {
		return fmt.Errorf("create staging directory: %w", err)
	}
	defer os.RemoveAll(staging)

	stagedTemplates := filepath.Join(staging, "templates")
	if err := exportTemplates(templatesSource, stagedTemplates); err != nil {
		return err
	}
	stagedFiles := filepath.Join(staging, "files")
	if info, statErr := os.Stat(filesSource); statErr == nil && info.IsDir() {
		if err := copyTree(filesSource, stagedFiles); err != nil {
			return fmt.Errorf("copy chart files: %w", err)
		}
	} else if statErr != nil && !os.IsNotExist(statErr) {
		return fmt.Errorf("validate source files: %w", statErr)
	}

	if err := replaceDirectory(stagedTemplates, filepath.Join(target, "templates", "agentio")); err != nil {
		return fmt.Errorf("replace generated templates: %w", err)
	}
	if err := replaceDirectory(stagedFiles, filepath.Join(target, "files", "agentio")); err != nil {
		return fmt.Errorf("replace generated files: %w", err)
	}
	if err := writeFileAtomically(targetValuesPath, nextValues, 0o644); err != nil {
		return fmt.Errorf("write target values: %w", err)
	}
	return nil
}

func validateSourceValues(content []byte) error {
	values := map[string]any{}
	if err := yaml.Unmarshal(content, &values); err != nil {
		return fmt.Errorf("parse source values: %w", err)
	}
	if _, found := values["enabled"]; found {
		return errors.New("source values contain a conflicting root-level enabled key")
	}
	return nil
}

func replaceValuesBlock(target, source []byte) ([]byte, error) {
	block := generatedValuesBlock(source)
	beginCount := bytes.Count(target, []byte(valuesBegin))
	endCount := bytes.Count(target, []byte(valuesEnd))
	if beginCount == 0 && endCount == 0 {
		out := append([]byte(nil), target...)
		if len(out) > 0 && out[len(out)-1] != '\n' {
			out = append(out, '\n')
		}
		if len(out) > 0 && !bytes.HasSuffix(out, []byte("\n\n")) {
			out = append(out, '\n')
		}
		return append(out, block...), nil
	}
	if beginCount != 1 || endCount != 1 {
		return nil, fmt.Errorf("target values must contain exactly one matching Agentio generated-values marker pair")
	}

	begin := bytes.Index(target, []byte(valuesBegin))
	end := bytes.Index(target, []byte(valuesEnd))
	if begin > end {
		return nil, errors.New("target values Agentio generated-values markers are out of order")
	}
	end += len(valuesEnd)
	if end < len(target) && target[end] == '\r' {
		end++
	}
	if end < len(target) && target[end] == '\n' {
		end++
	}

	out := make([]byte, 0, begin+len(block)+len(target)-end)
	out = append(out, target[:begin]...)
	out = append(out, block...)
	out = append(out, target[end:]...)
	return out, nil
}

func generatedValuesBlock(source []byte) []byte {
	source = bytes.TrimSuffix(source, []byte("\n"))
	var out bytes.Buffer
	fmt.Fprintln(&out, valuesBegin)
	fmt.Fprintln(&out, "agentio:")
	fmt.Fprintln(&out, "  enabled: false")
	for _, line := range bytes.Split(source, []byte("\n")) {
		if len(line) == 0 {
			out.WriteByte('\n')
			continue
		}
		out.WriteString("  ")
		out.Write(line)
		out.WriteByte('\n')
	}
	fmt.Fprintln(&out, valuesEnd)
	return out.Bytes()
}

func exportTemplates(source, target string) error {
	return filepath.WalkDir(source, func(path string, entry fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if entry.IsDir() {
			return nil
		}
		if entry.Type()&os.ModeSymlink != 0 {
			return fmt.Errorf("source template %q is a symlink", path)
		}
		rel, err := filepath.Rel(source, path)
		if err != nil {
			return fmt.Errorf("resolve source template path %q: %w", path, err)
		}

		ext := strings.ToLower(filepath.Ext(path))
		if ext != ".yaml" && ext != ".yml" && ext != ".tpl" {
			return fmt.Errorf("unsupported source template file %q", path)
		}
		content, err := os.ReadFile(path)
		if err != nil {
			return fmt.Errorf("read source template %q: %w", path, err)
		}
		if ext == ".tpl" {
			content, err = rewriteTemplate(content)
			if err != nil {
				return fmt.Errorf("rewrite source template %q: %w", path, err)
			}
			content = append([]byte(warning), content...)
		} else {
			helpers, resource, err := splitLeadingDefinitions(content)
			if err != nil {
				return fmt.Errorf("split source template %q: %w", path, err)
			}
			if definePattern.Match(resource) {
				return fmt.Errorf("resource template %q contains a non-leading named template definition", path)
			}
			helpers, err = rewriteTemplate(helpers)
			if err != nil {
				return fmt.Errorf("rewrite helpers in source template %q: %w", path, err)
			}
			resource, err = rewriteTemplate(resource)
			if err != nil {
				return fmt.Errorf("rewrite resources in source template %q: %w", path, err)
			}
			var guarded bytes.Buffer
			guarded.WriteString(warning)
			guarded.Write(helpers)
			if len(helpers) > 0 && helpers[len(helpers)-1] != '\n' {
				guarded.WriteByte('\n')
			}
			guardResource := filepath.ToSlash(rel) != "crds.yaml"
			if guardResource {
				guarded.WriteString("{{- if .Values.agentio.enabled }}\n")
			}
			guarded.Write(resource)
			if len(resource) > 0 && resource[len(resource)-1] != '\n' {
				guarded.WriteByte('\n')
			}
			if guardResource {
				guarded.WriteString("{{- end }}\n")
			}
			content = guarded.Bytes()
		}

		destination := filepath.Join(target, rel)
		if err := os.MkdirAll(filepath.Dir(destination), 0o755); err != nil {
			return fmt.Errorf("create generated template directory: %w", err)
		}
		if err := os.WriteFile(destination, content, 0o644); err != nil {
			return fmt.Errorf("write generated template %q: %w", destination, err)
		}
		return nil
	})
}

func splitLeadingDefinitions(content []byte) ([]byte, []byte, error) {
	position := 0
	helperEnd := 0
	for {
		start := position
		for start < len(content) && unicode.IsSpace(rune(content[start])) {
			start++
		}
		if start+2 > len(content) || !bytes.HasPrefix(content[start:], []byte("{{")) {
			break
		}
		end, err := templateActionEnd(content[start:])
		if err != nil {
			return nil, nil, err
		}
		if templateCommand(content[start:start+end]) != "define" {
			break
		}
		definitionEnd, err := matchingDefinitionEnd(content, start)
		if err != nil {
			return nil, nil, err
		}
		helperEnd = definitionEnd
		position = definitionEnd
	}
	return content[:helperEnd], content[helperEnd:], nil
}

func matchingDefinitionEnd(content []byte, start int) (int, error) {
	depth := 0
	position := start
	for position < len(content) {
		next := bytes.Index(content[position:], []byte("{{"))
		if next < 0 {
			break
		}
		next += position
		trimmed := bytes.TrimLeft(content[next+2:], "- \t\r\n")
		var end int
		var err error
		if bytes.HasPrefix(trimmed, []byte("/*")) {
			end, err = templateCommentEnd(content[next:])
		} else {
			end, err = templateActionEnd(content[next:])
		}
		if err != nil {
			return 0, err
		}
		command := templateCommand(content[next : next+end])
		switch command {
		case "define", "if", "range", "with", "block":
			depth++
		case "end":
			depth--
			if depth == 0 {
				return next + end, nil
			}
			if depth < 0 {
				return 0, errors.New("named template has an unmatched end action")
			}
		}
		position = next + end
	}
	return 0, errors.New("named template definition is not closed")
}

func templateCommand(action []byte) string {
	if len(action) < 4 {
		return ""
	}
	body := strings.TrimSpace(string(action[2 : len(action)-2]))
	body = strings.TrimSpace(strings.Trim(body, "-"))
	if body == "" || strings.HasPrefix(body, "/*") {
		return ""
	}
	command, _, _ := strings.Cut(body, " ")
	return command
}

func rewriteTemplate(content []byte) ([]byte, error) {
	var out bytes.Buffer
	for len(content) > 0 {
		start := bytes.Index(content, []byte("{{"))
		if start < 0 {
			out.Write(content)
			break
		}
		out.Write(content[:start])
		content = content[start:]
		trimmed := bytes.TrimLeft(content[2:], "- \t\r\n")
		var end int
		var err error
		if bytes.HasPrefix(trimmed, []byte("/*")) {
			end, err = templateCommentEnd(content)
		} else {
			end, err = templateActionEnd(content)
		}
		if err != nil {
			return nil, err
		}
		action := content[:end]
		if bytes.HasPrefix(trimmed, []byte("/*")) {
			out.Write(action)
		} else {
			rewritten := rewriteValuesReferences(action)
			rewritten = bytes.ReplaceAll(rewritten,
				[]byte(`"enhancedTrafficManagement.meshConfig"`),
				[]byte(`"agentio.meshConfig.defaults"`))
			rewritten = filesPattern.ReplaceAll(rewritten, []byte(`${1}"files/agentio/`))
			out.Write(rewritten)
		}
		content = content[end:]
	}
	return out.Bytes(), nil
}

func templateCommentEnd(action []byte) (int, error) {
	commentEnd := bytes.Index(action, []byte("*/"))
	if commentEnd < 0 {
		return 0, errors.New("unterminated Helm template comment")
	}
	for i := commentEnd + 2; i+1 < len(action); i++ {
		if action[i] == '}' && action[i+1] == '}' {
			return i + 2, nil
		}
		if action[i] != '-' && action[i] != ' ' && action[i] != '\t' && action[i] != '\r' && action[i] != '\n' {
			break
		}
	}
	return 0, errors.New("invalid Helm template comment terminator")
}

func templateActionEnd(action []byte) (int, error) {
	var quote byte
	escaped := false
	for i := 2; i+1 < len(action); i++ {
		ch := action[i]
		if quote != 0 {
			if quote != '`' && escaped {
				escaped = false
				continue
			}
			if quote != '`' && ch == '\\' {
				escaped = true
				continue
			}
			if ch == quote {
				quote = 0
			}
			continue
		}
		if ch == '"' || ch == '\'' || ch == '`' {
			quote = ch
			continue
		}
		if ch == '}' && action[i+1] == '}' {
			return i + 2, nil
		}
	}
	return 0, errors.New("unterminated Helm template action")
}

func rewriteValuesReferences(action []byte) []byte {
	const token = ".Values"
	var out bytes.Buffer
	var quote byte
	escaped := false
	for i := 0; i < len(action); {
		ch := action[i]
		if quote != 0 {
			out.WriteByte(ch)
			i++
			if quote != '`' && escaped {
				escaped = false
				continue
			}
			if quote != '`' && ch == '\\' {
				escaped = true
				continue
			}
			if ch == quote {
				quote = 0
			}
			continue
		}
		if ch == '"' || ch == '\'' || ch == '`' {
			quote = ch
			out.WriteByte(ch)
			i++
			continue
		}
		if strings.HasPrefix(string(action[i:]), token) && valueTokenBoundary(action, i, len(token)) {
			out.WriteString(token)
			if !hasAgentioSegment(action[i+len(token):]) {
				out.WriteString(".agentio")
			}
			i += len(token)
			continue
		}
		out.WriteByte(ch)
		i++
	}
	return out.Bytes()
}

func hasAgentioSegment(content []byte) bool {
	const segment = ".agentio"
	if !bytes.HasPrefix(content, []byte(segment)) {
		return false
	}
	if len(content) == len(segment) {
		return true
	}
	next := rune(content[len(segment)])
	return !unicode.IsLetter(next) && !unicode.IsDigit(next) && next != '_'
}

func valueTokenBoundary(content []byte, start, length int) bool {
	if start > 0 {
		previous := rune(content[start-1])
		if unicode.IsLetter(previous) || unicode.IsDigit(previous) || previous == '_' {
			return false
		}
	}
	end := start + length
	if end < len(content) {
		next := rune(content[end])
		if unicode.IsLetter(next) || unicode.IsDigit(next) || next == '_' {
			return false
		}
	}
	return true
}

func copyTree(source, target string) error {
	return filepath.WalkDir(source, func(path string, entry fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if entry.Type()&os.ModeSymlink != 0 {
			return fmt.Errorf("source file %q is a symlink", path)
		}
		rel, err := filepath.Rel(source, path)
		if err != nil {
			return err
		}
		destination := filepath.Join(target, rel)
		if entry.IsDir() {
			return os.MkdirAll(destination, 0o755)
		}
		content, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if err := os.MkdirAll(filepath.Dir(destination), 0o755); err != nil {
			return err
		}
		return os.WriteFile(destination, content, 0o644)
	})
}

func replaceDirectory(source, target string) error {
	if err := os.RemoveAll(target); err != nil {
		return err
	}
	if _, err := os.Stat(source); os.IsNotExist(err) {
		return nil
	} else if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(target), 0o755); err != nil {
		return err
	}
	return os.Rename(source, target)
}

func writeFileAtomically(path string, content []byte, mode fs.FileMode) error {
	temporary, err := os.CreateTemp(filepath.Dir(path), ".agentio-values-")
	if err != nil {
		return err
	}
	temporaryName := temporary.Name()
	defer os.Remove(temporaryName)
	if err := temporary.Chmod(mode); err != nil {
		temporary.Close()
		return err
	}
	if _, err := temporary.Write(content); err != nil {
		temporary.Close()
		return err
	}
	if err := temporary.Close(); err != nil {
		return err
	}
	return os.Rename(temporaryName, path)
}
